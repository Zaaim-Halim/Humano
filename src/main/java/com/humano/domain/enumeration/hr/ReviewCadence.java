package com.humano.domain.enumeration.hr;

/**
 * How often the company reviews performance.
 */
public enum ReviewCadence {
    /**
     * One review a year, covering the whole review year.
     */
    ANNUAL,

    /**
     * A mid-year and a year-end review, each covering half of the review year.
     */
    SEMI_ANNUAL,
}
