import { HttpClient } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable } from 'rxjs';

import { ApplicationConfigService } from 'app/core/config/application-config.service';
import { createRequestOption } from 'app/core/request/request-util';

import { CreatePayrollCalendarRequest, PayrollCalendar } from '../models/payroll-calendar.model';

/** Payroll calendars — `/api/payroll/calendars` (gated `CONFIGURE_PAYROLL_CALENDAR`). */
@Injectable({ providedIn: 'root' })
export class PayrollCalendarService {
  private readonly http = inject(HttpClient);
  private readonly resourceUrl = inject(ApplicationConfigService).getEndpointFor('api/payroll/calendars');

  /** `GET /api/payroll/calendars/active` — active calendars, each with its upcoming periods. */
  active(): Observable<PayrollCalendar[]> {
    return this.http.get<PayrollCalendar[]>(`${this.resourceUrl}/active`);
  }

  /** `POST /api/payroll/calendars` — a new calendar; its periods are generated by the backend. */
  create(body: CreatePayrollCalendarRequest): Observable<PayrollCalendar> {
    return this.http.post<PayrollCalendar>(this.resourceUrl, body);
  }

  /** `POST /api/payroll/calendars/{id}/active?active=` — switch a calendar on or off. */
  setActive(id: string, active: boolean): Observable<PayrollCalendar> {
    return this.http.post<PayrollCalendar>(`${this.resourceUrl}/${encodeURIComponent(id)}/active`, null, {
      params: createRequestOption({ active }),
    });
  }
}
